def validate_model_shape_and_parameters(profile: Any) -> dict[str, Any]:
    from qrwkv_xla.scale_planner import (
        estimate_qwen_reference_parameters,
        validate_model_profile,
    )

    warnings: list[str] = []
    errors: list[str] = []
    try:
        validate_model_profile(profile)
    except ValueError as exc:
        errors.append(str(exc))
    params = estimate_qwen_reference_parameters(profile)
    shapes = parameter_shape_metadata(profile)["shapes"]
    for name, shape in shapes.items():
        if any(dim <= 0 for dim in shape):
            errors.append(f"{name} contains non-positive dimensions: {shape}")
    if shapes["token_embedding.weight"] != [profile.vocab_size, profile.hidden_size]:
        errors.append("token embedding shape does not match vocab/hidden size")
    if profile.kv_hidden_size > profile.hidden_size:
        warnings.append("kv hidden size exceeds hidden size")
    if profile.name.endswith("7b_stretch"):
        warnings.append("7B stretch shape is metadata-only unless sharding is added.")
    band = parameter_band_status(profile.name, params.total_params)
    if band["status"] == "out_of_band_warning":
        warnings.append("Estimated parameter count is outside the expected band.")
    warnings.extend(validation_warnings(profile, params.total_params))
    return {
        "status": "fail" if errors else "pass_with_warnings" if warnings else "pass",
        "errors": errors,
        "warnings": list(dict.fromkeys(warnings)),
        "parameter_band_status": band,
        "checked_shape_count": len(shapes),
    }


def parameter_band_status(model_name: str, total_parameters: int) -> dict[str, Any]:
    band = EXPECTED_PARAMETER_BANDS.get(model_name)
    if band is None:
        return {
            "status": "not_applicable",
            "total_parameters": total_parameters,
        }
    ok = int(band["minimum"]) <= total_parameters <= int(band["maximum"])
    return {
        **band,
        "total_parameters": total_parameters,
        "status": "in_band" if ok else "out_of_band_warning",
    }


def validation_warnings(profile: Any, total_parameters: int) -> list[str]:
    warnings = [
        "Planning-only / dry-run-only output; no real training was run.",
        "Default metadata-only path does not materialize full parameter arrays.",
    ]
    if profile.name.endswith("7b_stretch"):
        warnings.append("7B stretch profile is not claimed to train on one device.")
    band = parameter_band_status(profile.name, total_parameters)
    if band["status"] == "out_of_band_warning":
        warnings.append("Estimated parameter count is outside the expected band.")
    return warnings


