def write_checkpoint_skeleton_bundle(
    output_dir: str | Path, profile: Any, total_parameters: int
) -> dict[str, Any]:
    from qrwkv_xla.tracking.json_io import write_json

    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    metadata = checkpoint_skeleton_payload(profile, total_parameters)
    model_config = {
        "planning_only": True,
        "profile_name": profile.name,
        "student": model_config_payload(profile),
    }
    metadata_path = write_json(out / "checkpoint_metadata.json", metadata)
    model_config_path = out / "model_config.yaml"
    model_config_path.write_text(
        yaml.safe_dump(model_config, sort_keys=False), encoding="utf-8"
    )
    manifest = {
        "schema_version": "p45-checkpoint-manifest-v1",
        "created_by": P45_CREATED_BY,
        "status": "metadata_only_checkpoint_skeleton",
        "profile_name": profile.name,
        "files": {
            "model_config": "model_config.yaml",
            "checkpoint_metadata": "checkpoint_metadata.json",
        },
        "expected_total_parameters": total_parameters,
        "planning_only": True,
        "dry_run_only": True,
    }
    manifest_path = write_json(out / "checkpoint_manifest.json", manifest)
    readback = validate_checkpoint_skeleton_bundle(out)
    return {
        "enabled": True,
        "status": "validated" if readback["status"] == "valid" else "invalid",
        "validated": readback["status"] == "valid",
        "manifest_path": str(manifest_path),
        "model_config_path": str(model_config_path),
        "metadata_path": str(metadata_path),
        "readback": readback,
    }


def validate_checkpoint_skeleton(path: str | Path) -> bool:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    return _validate_checkpoint_metadata(payload)["status"] == "valid"


def validate_checkpoint_skeleton_bundle(path: str | Path) -> dict[str, Any]:
    root = Path(path)
    errors: list[str] = []
    manifest_path = root / "checkpoint_manifest.json"
    model_config_path = root / "model_config.yaml"
    metadata_path = root / "checkpoint_metadata.json"
    for required_path in (manifest_path, model_config_path, metadata_path):
        if not required_path.is_file():
            errors.append(f"missing {required_path.name}")
    if errors:
        return {"status": "invalid", "errors": errors}

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    model_config = yaml.safe_load(model_config_path.read_text(encoding="utf-8"))
    metadata_status = _validate_checkpoint_metadata(metadata)
    if metadata_status["status"] != "valid":
        errors.extend(metadata_status["errors"])
    if manifest.get("schema_version") != "p45-checkpoint-manifest-v1":
        errors.append("invalid manifest schema_version")
    if model_config.get("planning_only") is not True:
        errors.append("model_config planning_only must be true")
    if manifest.get("profile_name") != model_config.get("profile_name"):
        errors.append("manifest/model_config profile mismatch")
    return {
        "status": "valid" if not errors else "invalid",
        "errors": errors,
        "profile_name": manifest.get("profile_name"),
        "files_read": [
            str(manifest_path),
            str(model_config_path),
            str(metadata_path),
        ],
    }


