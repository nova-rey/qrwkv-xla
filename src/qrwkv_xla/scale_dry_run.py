def generate_multiscale_configs(
    output_dir: str | Path = P45_DEFAULT_ARTIFACT_DIR,
    *,
    model_profiles: tuple[str, ...] = P45_TARGET_MODEL_PROFILES,
    hardware_profiles: tuple[str, ...] = P45_HARDWARE_PROFILES,
    training_mode_name: str = P45_TRAINING_MODE,
    batch_size: int = 1,
    overwrite: bool = False,
) -> dict[str, Path]:
    from qrwkv_xla.scale_planner import (
        ScalePlanRequest,
        distill_config_yaml,
        make_plan,
        plan_to_dict,
        resolve_hardware_profile,
        resolve_model_profile,
        resolve_training_mode,
    )
    from qrwkv_xla.tracking.json_io import write_json

    out = _prepare_output_dir(output_dir, overwrite=overwrite)
    config_dir = out / "configs"
    config_dir.mkdir(parents=True, exist_ok=True)

    mode = resolve_training_mode(training_mode_name)
    plans: list[dict[str, Any]] = []
    validations: dict[str, Any] = {}
    fit_matrix: dict[str, Any] = {
        "phase": "P45",
        "status": "planning_only_and_dry_run_only",
        "created_by": P45_CREATED_BY,
        "training_mode": training_mode_name,
        "models": {},
        "memory_units": "bytes_and_gibibytes",
        "caveats": _caveats(),
    }

    for model_name in model_profiles:
        model = resolve_model_profile(model_name)
        validation = validate_model_shape_and_parameters(model)
        validations[model_name] = validation
        model_plans: dict[str, Any] = {}
        representative_plan = None
        for hardware_name in hardware_profiles:
            hardware = resolve_hardware_profile(hardware_name)
            plan = make_plan(
                ScalePlanRequest(
                    model_profile=model,
                    hardware_profile=hardware,
                    training_mode=mode,
                    sequence_length=model.sequence_length_default,
                    batch_size=batch_size,
                    microbatch_size=1,
                    grad_accum_steps=max(1, batch_size),
                )
            )
            plan_dict = plan_to_dict(plan)
            plan_dict["expected_parameter_band"] = parameter_band_status(
                model_name, plan.parameter_estimate.total_params
            )
            plan_dict["shape_parameter_validation"] = validation
            plans.append(plan_dict)
            model_plans[hardware_name] = fit_matrix_cell(plan_dict)
            if representative_plan is None:
                representative_plan = plan
        fit_matrix["models"][model_name] = model_plans
        if representative_plan is not None:
            config_text = distill_config_yaml(representative_plan)
            config_text = config_text.replace(
                "# Generated by P34 scale planner.\n",
                "# Generated by P45 multi-scale config dry-run.\n",
            )
            config_text = config_text.replace(
                "# Planning estimate only; not hardware-validated.\n",
                "# Planning estimate only; P45 dry-run config, "
                "not hardware-validated.\n",
            )
            (config_dir / f"{model_name}.yaml").write_text(
                config_text, encoding="utf-8"
            )

    report = {
        "phase": "P45",
        "status": "planning_only_and_dry_run_only",
        "created_by": P45_CREATED_BY,
        "artifact_dir": str(out),
        "model_profiles": list(model_profiles),
        "hardware_profiles": list(hardware_profiles),
        "training_mode": training_mode_name,
        "safe_init_policy": safe_init_policy(),
        "shape_parameter_validation": validations,
        "caveats": _caveats(),
        "recommended_first_real_qwen0_5b_run": first_real_qwen_0_5b_summary(),
        "plans": plans,
    }
    paths = {
        "scale_plan_report": write_json(out / "scale_plan_report.json", report),
        "fit_matrix": write_json(out / "fit_matrix.json", fit_matrix),
        "markdown_report": _write_scale_plan_markdown(
            out / "P45_SCALE_PLAN_REPORT.md", report, fit_matrix
        ),
    }
    _write_results_markdown(out / "P45_RESULTS.md", report, fit_matrix, None)
    return paths


def run_shape_dry_run(
    output_dir: str | Path = P45_DEFAULT_ARTIFACT_DIR,
    *,
    model_profiles: tuple[str, ...] = P45_TARGET_MODEL_PROFILES,
    hardware_profiles: tuple[str, ...] = P45_HARDWARE_PROFILES,
    metadata_only: bool = True,
    materialize_init: bool = False,
    allow_large_materialization: bool = False,
    checkpoint_skeleton: bool = True,
    scale_plan_path: str | Path | None = None,
    overwrite: bool = False,
) -> dict[str, Any]:
    from qrwkv_xla.scale_planner import (
        estimate_qwen_reference_parameters,
        resolve_model_profile,
    )
    from qrwkv_xla.tracking.json_io import write_json

    plan_payload = _load_scale_plan(scale_plan_path)
    out = _prepare_dry_run_output_dir(output_dir, overwrite=overwrite)
    selected_models = _profiles_from_scale_plan(plan_payload) or list(model_profiles)
    selected_hardware = _hardware_from_scale_plan(plan_payload) or list(
        hardware_profiles
    )
    fit_by_model = _fit_by_model_from_scale_plan(plan_payload)
    if not fit_by_model:
        fit_by_model = build_fit_by_model(
            tuple(selected_models),
            tuple(selected_hardware),
            P45_TRAINING_MODE,
        )

    results = []
    for model_name in selected_models:
        profile = resolve_model_profile(model_name)
        params = estimate_qwen_reference_parameters(profile)
        validation = validate_model_shape_and_parameters(profile)
        materialized = False
        materialization_status = "metadata_only_not_requested"
        if materialize_init:
            if _allows_materialization(profile, allow_large_materialization):
                _materialize_tiny_params(profile)
                materialized = True
                materialization_status = "materialized"
            else:
                materialization_status = "blocked_by_safe_init_policy"

        skeleton_status = {
            "enabled": checkpoint_skeleton,
            "status": "skipped",
            "manifest_path": None,
            "model_config_path": None,
            "metadata_path": None,
            "readback": None,
        }
        if checkpoint_skeleton:
            skeleton_status = write_checkpoint_skeleton_bundle(
                out / "checkpoint_skeletons" / model_name,
                profile,
                params.total_params,
            )

        item = {
            "phase": "P45",
            "model_profile": model_name,
            "status": "metadata_only_validated" if metadata_only else "validated",
            "metadata_only": metadata_only,
            "materialized": materialized,
            "materialization_status": materialization_status,
            "safe_init_policy": safe_init_policy(),
            "config": model_config_payload(profile),
            "parameter_estimate": {
                "total_parameters": params.total_params,
                "components": params.components,
                "assumptions": params.assumptions,
            },
            "expected_parameter_band": parameter_band_status(
                model_name, params.total_params
            ),
            "shape_parameter_validation": validation,
            "shape_metadata": parameter_shape_metadata(profile),
            "state_metadata": recurrent_state_metadata(profile),
            "fit_by_hardware": fit_by_model.get(model_name, {}),
            "checkpoint_skeleton": skeleton_status,
            "warnings": validation["warnings"],
            "caveats": _caveats(),
        }
        write_json(out / "dry_runs" / model_name / "metadata_dry_run.json", item)
        results.append(item)

    payload = {
        "phase": "P45",
        "status": "dry_run_only",
        "created_by": P45_CREATED_BY,
        "artifact_dir": str(out),
        "default_safe": True,
        "metadata_only_default": True,
        "materialize_init_requested": materialize_init,
        "allow_large_materialization": allow_large_materialization,
        "scale_plan_input": str(scale_plan_path) if scale_plan_path else None,
        "safe_init_policy": safe_init_policy(),
        "caveats": _caveats(),
        "dry_runs": results,
    }
    write_json(out / "multiscale_shape_dry_run_report.json", payload)
    _write_dry_run_markdown(out / "P45_DRY_RUN_REPORT.md", payload)
    _write_results_markdown(out / "P45_RESULTS.md", plan_payload, None, payload)
    return payload


def build_fit_by_model(
    model_profiles: tuple[str, ...],
    hardware_profiles: tuple[str, ...],
    training_mode_name: str,
) -> dict[str, dict[str, Any]]:
    from qrwkv_xla.scale_planner import (
        ScalePlanRequest,
        make_plan,
        plan_to_dict,
        resolve_hardware_profile,
        resolve_model_profile,
        resolve_training_mode,
    )

    mode = resolve_training_mode(training_mode_name)
    rows: dict[str, dict[str, Any]] = {}
    for model_name in model_profiles:
        model = resolve_model_profile(model_name)
        rows[model_name] = {}
        for hardware_name in hardware_profiles:
            hardware = resolve_hardware_profile(hardware_name)
            plan = make_plan(
                ScalePlanRequest(
                    model_profile=model,
                    hardware_profile=hardware,
                    training_mode=mode,
                    sequence_length=model.sequence_length_default,
                    batch_size=1,
                    microbatch_size=1,
                    grad_accum_steps=1,
                )
            )
            rows[model_name][hardware_name] = fit_matrix_cell(plan_to_dict(plan))
    return rows


def fit_matrix_cell(plan_dict: dict[str, Any]) -> dict[str, Any]:
    memory = plan_dict["memory_estimate"]
    components = memory["components"]
    hardware = plan_dict["hardware_profile"]
    fit = plan_dict["fit"]
    component_bytes = {
        "estimated_parameter_memory": components["weights"],
        "estimated_optimizer_memory": (
            components["gradients"] + components["optimizer_state"]
        ),
        "activation_sequence_memory_estimate": (
            components["activations_estimate"]
            + components["wkv_recurrent_state"]
            + components["shift_state"]
            + components["input_ids_and_masks"]
        ),
        "target_logits_hidden_target_memory_estimate": (
            components["teacher_hidden_targets_per_batch"]
            + components["teacher_logits_targets_per_batch"]
        ),
        "checkpoint_memory_estimate": components["checkpoint_size_estimate"],
        "xla_overhead_reserve": components["xla_overhead_reserve"],
        "total_estimate": memory["total_bytes"],
    }
    interpretation = memory_interpretation(hardware)
    classification = fit["fit"]
    notes = _fit_notes(plan_dict, interpretation)
    return {
        "memory_fit": classification,
        "fit_classification": classification,
        "metadata_only_dry_run_status": "supported",
        "dry_run_support": "metadata_only",
        "recommended_training_mode": recommended_training_mode(
            classification, plan_dict, interpretation
        ),
        "memory_interpretation": interpretation,
        "estimated_total_gb": fit["estimated_total_gb"],
        "available_memory_gb": fit["available_memory_gb"],
        "safety_margin_gb": fit["safety_margin_gb"],
        "utilization": fit["utilization"],
        "limiting_factor": fit["limiting_factor"],
        "component_estimates_bytes": component_bytes,
        "component_estimates_gib": {
            key: round(value / (1024**3), 4) for key, value in component_bytes.items()
        },
        "notes": notes,
        "warning": "; ".join(notes),
        "planner_warnings": fit["warnings"],
    }


def recommended_training_mode(
    classification: str, plan_dict: dict[str, Any], interpretation: str
) -> str:
    model_name = plan_dict["model_profile"]["name"]
    hardware = plan_dict["hardware_profile"]
    if classification == "no":
        return "not_recommended"
    if model_name.endswith("7b_stretch"):
        return (
            "hidden_only"
            if "requires_pjit_sharding" in interpretation
            else "not_recommended"
        )
    if hardware["device_count"] >= 32 and classification in {"yes", "maybe"}:
        return "hidden_plus_topk_logits"
    if classification == "yes" and hardware["device_kind"] == "gpu":
        return "hidden_plus_full_logits"
    return "hidden_only"


def memory_interpretation(hardware: dict[str, Any]) -> str:
    if hardware["device_kind"] == "tpu" and hardware["device_count"] > 1:
        if hardware.get("supports_pjit"):
            return "aggregate_slice_requires_pjit_sharding"
        return "aggregate_slice_metadata_only_no_pjit_runtime"
    return "single_device_estimate"


def parameter_shape_metadata(profile: Any) -> dict[str, Any]:
    layers = profile.num_layers
    hidden = profile.hidden_size
    kv_hidden = profile.kv_hidden_size
    mlp = profile.effective_mlp_hidden_size
    shapes: dict[str, Any] = {
        "token_embedding.weight": [profile.vocab_size, hidden],
        "layers.input_layernorm.weight": [layers, hidden],
        "layers.post_attention_layernorm.weight": [layers, hidden],
        "layers.self_attn.q_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.k_proj.weight": [layers, hidden, kv_hidden],
        "layers.self_attn.v_proj.weight": [layers, hidden, kv_hidden],
        "layers.self_attn.w_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.a_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.b_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.g_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.o_proj.weight": [layers, hidden, hidden],
        "layers.self_attn.time_bias": [layers, hidden],
        "layers.self_attn.time_mix": [layers, hidden],
        "layers.mlp.gate_proj.weight": [layers, hidden, mlp],
        "layers.mlp.up_proj.weight": [layers, hidden, mlp],
        "layers.mlp.down_proj.weight": [layers, mlp, hidden],
        "final_layernorm.weight": [hidden],
    }
    if profile.emit_logits and not profile.tie_embeddings:
        shapes["lm_head.weight"] = [hidden, profile.vocab_size]
        shapes["lm_head.bias"] = [profile.vocab_size]
    elif profile.emit_logits:
        shapes["lm_head_bias"] = [profile.vocab_size]
    return {
        "backend": profile.backend,
        "dtype_default": profile.dtype_default,
        "shapes": shapes,
    }


