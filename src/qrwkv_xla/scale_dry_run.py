def _prepare_output_dir(output_dir: str | Path, *, overwrite: bool) -> Path:
    out = Path(output_dir)
    if overwrite and out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)
    return out


def _prepare_dry_run_output_dir(output_dir: str | Path, *, overwrite: bool) -> Path:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    if overwrite:
        for child in (
            out / "dry_runs",
            out / "checkpoint_skeletons",
            out / "multiscale_shape_dry_run_report.json",
            out / "P45_DRY_RUN_REPORT.md",
            out / "P45_RESULTS.md",
        ):
            if child.is_dir():
                shutil.rmtree(child)
            elif child.exists():
                child.unlink()
    return out


